    /// Where to anchor a callout for each district: the centroid of its largest
    /// ring, which for these shapes always lands inside the district.
    static let centroids: [District: CGPoint] = {
        var out: [District: CGPoint] = [:]
        for (district, rings) in outlines {
            guard let ring = rings.max(by: { $0.count < $1.count }), ring.count > 2 else { continue }
            var area: CGFloat = 0, cx: CGFloat = 0, cy: CGFloat = 0
            for i in ring.indices {
                let a = ring[i], b = ring[(i + 1) % ring.count]
                let cross = a.x * b.y - b.x * a.y
                area += cross
                cx += (a.x + b.x) * cross
                cy += (a.y + b.y) * cross
            }
            if abs(area) < 1e-9 { continue }
            out[district] = CGPoint(x: cx / (3 * area), y: cy / (3 * area))
        }
        return out
    }()
